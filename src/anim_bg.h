static const uint8_t ANIM_BAYER[16] = {0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5};

/* Mélange de deux couleurs RGB565 : k = 0 pour a, 255 pour b. */
static uint16_t mix565(uint16_t a, uint16_t b, int k) {
  int ar = (a >> 11) & 31, ag = (a >> 5) & 63, ab = a & 31;
  int br = (b >> 11) & 31, bg = (b >> 5) & 63, bb = b & 31;
  int r = (ar * (255 - k) + br * k) / 255;
  int g = (ag * (255 - k) + bg * k) / 255;
  int bl = (ab * (255 - k) + bb * k) / 255;
  return (uint16_t)((r << 11) | (g << 5) | bl);
}

/* Couleur de fond à l'instant t (ms) pour le pixel (x, y) : interpolation dans le temps et
 * entre les lignes, puis trame de Bayer pour éviter les bandes. */
static uint16_t anim_bg565(int t, int x, int y) {
  if (t < 0) t = 0;
  if (t > ANIM_TMAX) t = ANIM_TMAX;
  int ft = t * (ANIM_NT - 1) * 256 / ANIM_TMAX;
  int it = ft >> 8, wt = ft & 255;
  if (it >= ANIM_NT - 1) { it = ANIM_NT - 2; wt = 256; }
  int fy = y * (ANIM_NR - 1) * 256 / 239;
  int iy = fy >> 8, wy = fy & 255;
  if (iy >= ANIM_NR - 1) { iy = ANIM_NR - 2; wy = 256; }
  int w[4] = { (256 - wt) * (256 - wy), (256 - wt) * wy, wt * (256 - wy), wt * wy };
  const uint8_t *p[4] = { ANIM_TAB[it][iy], ANIM_TAB[it][iy + 1], ANIM_TAB[it + 1][iy], ANIM_TAB[it + 1][iy + 1] };
  int c[3] = {0, 0, 0};
  for (int k = 0; k < 4; k++)
    for (int ch = 0; ch < 3; ch++) c[ch] += p[k][ch] * w[k];
  int b4 = ANIM_BAYER[(y & 3) * 4 + (x & 3)];
  int r8 = (c[0] + 32768) >> 16, g8 = (c[1] + 32768) >> 16, b8 = (c[2] + 32768) >> 16;
  int r5 = (r8 * 31 * 16 / 255 + b4) / 16;
  int g6 = (g8 * 63 * 16 / 255 + b4) / 16;
  int b5 = (b8 * 31 * 16 / 255 + b4) / 16;
  if (r5 > 31) r5 = 31;
  if (g6 > 63) g6 = 63;
  if (b5 > 31) b5 = 31;
  return (uint16_t)((r5 << 11) | (g6 << 5) | b5);
}

