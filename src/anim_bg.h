/* Couleur d'un pixel de la ligne y à l'instant t (ms), interpolée dans le temps et entre les lignes. */
static uint16_t anim_bg565(int t, int y) {
  if (t < 0) t = 0;
  if (t > ANIM_TMAX) t = ANIM_TMAX;
  int ft = t * (ANIM_NT - 1) * 256 / ANIM_TMAX;
  int it = ft >> 8, wt = ft & 255;
  if (it >= ANIM_NT - 1) { it = ANIM_NT - 2; wt = 256; }
  int fy = y * (ANIM_NR - 1) * 256 / 239;
  int iy = fy >> 8, wy = fy & 255;
  if (iy >= ANIM_NR - 1) { iy = ANIM_NR - 2; wy = 256; }
  uint16_t c[4] = { ANIM_TAB[it][iy], ANIM_TAB[it][iy + 1], ANIM_TAB[it + 1][iy], ANIM_TAB[it + 1][iy + 1] };
  int w[4] = { (256 - wt) * (256 - wy), (256 - wt) * wy, wt * (256 - wy), wt * wy };
  int r = 0, g = 0, b = 0;
  for (int k = 0; k < 4; k++) {
    r += ((c[k] >> 11) & 31) * w[k];
    g += ((c[k] >> 5) & 63) * w[k];
    b += (c[k] & 31) * w[k];
  }
  r = (r + 32768) >> 16;
  g = (g + 32768) >> 16;
  b = (b + 32768) >> 16;
  return (uint16_t)((r << 11) | (g << 5) | b);
}

