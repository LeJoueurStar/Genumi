static uint32_t utf8_cp(const char *s, int n) {
  const unsigned char *u = (const unsigned char *)s;
  if (n == 1) return u[0];
  if (n == 2) return ((u[0] & 0x1F) << 6) | (u[1] & 0x3F);
  if (n == 3) return ((u[0] & 0x0F) << 12) | ((u[1] & 0x3F) << 6) | (u[2] & 0x3F);
  return 0xFFFFFFFFu;
}

/* Renvoie les données hexadécimales du caractère, ou celles du '?' si absent. */
static const char *glyph_lookup(const char *s, int n) {
  uint32_t cp = utf8_cp(s, n);
  for (int i = 0; i < FONT_COUNT; i++)
    if (FONT_CP[i] == cp) return FONT_HEX + i * FNT_H * 2;
  for (int i = 0; i < FONT_COUNT; i++)
    if (FONT_CP[i] == '?') return FONT_HEX + i * FNT_H * 2;
  return FONT_HEX;
}

static int hexnib(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'A' && c <= 'F') return c - 'A' + 10;
  return 0;
}

